// Self-checking 64-point IFFT testbench.
// Golden model: y[m] = conj( (1/64) * sum_k conj(x[k]) * exp(-j*2*pi*k*m/64) ),
// Q1.15. The bit-reversal permute inside the FFT core and the one in
// bit_reversal_buffer cancel, so output comes back in natural order.
// The radix-2^2 core rounds at every butterfly (>>>1) and multiply (>>>15),
// so TOLERANCE absorbs that accumulated truncation.

module tb_ifft_64;
    localparam TOLERANCE = 24;   // LSB, covers per-stage rounding drift

    reg clk = 0, rst = 1, di_en = 0;
    reg  [15:0] di_re = 0, di_im = 0;
    wire        do_en;
    wire [15:0] do_re, do_im;

    integer errors = 0;
    integer i, k, outn, waited;
    reg signed [15:0] exp_re [0:63];
    reg signed [15:0] exp_im [0:63];
    reg signed [15:0] act_re [0:63];
    reg signed [15:0] act_im [0:63];
    reg        [15:0] stim_re [0:63];
    reg        [15:0] stim_im [0:63];
    reg signed [31:0] dr, di;
    integer max_err;

    always #5 clk = ~clk;

    ifft_64 dut (
        .clk(clk), .rst(rst),
        .di_en(di_en), .di_re(di_re), .di_im(di_im),
        .do_en(do_en), .do_re(do_re), .do_im(do_im)
    );

    // NBA-safe capture
    always @(posedge clk) begin
        if (do_en && !rst && outn < 64) begin
            act_re[outn] = do_re;
            act_im[outn] = do_im;
            outn = outn + 1;
        end
    end

    task run_case(input [8*16-1:0] name, input integer tol);
        begin
            @(negedge clk);
            rst <= 1'b1; @(negedge clk); rst <= 1'b0; @(negedge clk);
            outn = 0; max_err = 0;
            for (k = 0; k < 64; k = k + 1) begin
                @(negedge clk);
                di_en = 1'b1; di_re = stim_re[k]; di_im = stim_im[k];
            end
            @(negedge clk); di_en = 1'b0; di_re = 0; di_im = 0;
            waited = 0;
            while (outn < 64 && waited < 400) begin
                @(negedge clk); waited = waited + 1;
            end
            if (outn != 64) begin
                $display("  [FAIL] %0s: got %0d outputs, expected 64", name, outn);
                errors = errors + 1;
            end else begin
                for (i = 0; i < 64; i = i + 1) begin
                    dr = $signed(act_re[i]) - $signed(exp_re[i]);
                    if (dr < 0) dr = -dr;
                    if (dr > max_err) max_err = dr;
                    if (dr > tol) begin
                        $display("  [FAIL] %0s [%0d] re exp=%0d act=%0d diff=%0d", name, i, $signed(exp_re[i]), $signed(act_re[i]), dr);
                        errors = errors + 1;
                    end
                    di = $signed(act_im[i]) - $signed(exp_im[i]);
                    if (di < 0) di = -di;
                    if (di > max_err) max_err = di;
                    if (di > tol) begin
                        $display("  [FAIL] %0s [%0d] im exp=%0d act=%0d diff=%0d", name, i, $signed(exp_im[i]), $signed(act_im[i]), di);
                        errors = errors + 1;
                    end
                end
                if (max_err <= tol)
                    $display("  [PASS] %0s: 64 samples, max err %0d LSB (tol %0d)", name, max_err, tol);
            end
            repeat (250) @(negedge clk);
        end
    endtask

